export type OrderStatus = "pending" | "printing" | "quality-check" | "shipped";

export interface OrderBookItem {
  title: string;
  quantity: number;
  pages: number;
  cover: "softcover" | "hardcover";
}

export interface Order {
  id: string;
  userId: number;
  supplierId: number;
  items: OrderBookItem[];
  subTotal: number;
  discountAmount: number;
  couponCode: string | null;
  totalAmount: number;
  depositAmount: number;
  paidAmount: number;
  paymentType: "FULL" | "HALF";
  paymentStatus: "UNPAID" | "PARTIAL" | "PAID";
  customer: string;
  email: string;
  phone: string;
  address: string;
  city: string | null;
  orderShippingFee: number | null;
  supplierShippingFee: number | null;
  trackingCode: string | null;
  status: OrderStatus;
  date: string; 
  updatedAt: string;
  notes: string;
  timeline: { date: string; label: string }[];
}

export const totalCopies = (o: Order) => o.items.reduce((s, i) => s + i.quantity, 0);
export const remainingAmount = (o: Order) => Math.max(0, o.totalAmount - o.paidAmount);

